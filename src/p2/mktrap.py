"""Write lean/TrapData.lean: the main trap (cells 1..16) as a Lean list of (age, boundary value, strip).
age = steps since the last event (boundary value 0 and cell 1 = 1). Reads results/p2/walls/cert_T35.txt.
Lean re-checks everything, so this script is not trusted."""
import os
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.join(here, '..', '..')
k = 16; C = set()
for line in open(os.path.join(root, 'results', 'p2', 'walls', 'cert_T35.txt')):
    if line.startswith('#'): continue
    p, s = line.split(); C.add((int(p), int(s)))
def nxt(c, s, f):
    full = s | (f << k)
    return (1 - c, (((s << 1) | c) ^ (full | (full >> 1))) & ((1 << k) - 1))
ev = lambda a: a[0] == 0 and a[1] & 1
S = set((0, a) for a in C if ev(a)); q = list(S)
while q:
    age, a = q.pop()
    for f in (0, 1):
        b = nxt(a[0], a[1], f); nb = (0, b) if ev(b) else (age + 1, b)
        if nb not in S: S.add(nb); q.append(nb)
assert all(c == age % 2 for age, (c, s_) in S)   # the center value is the parity of the age
out = ["/-! Generated by `src/p2/mktrap.py` from `results/p2/walls/cert_T35.txt`. Data only; `Trap.lean` checks it. -/", "",
       f"/-- the main trap: {len(S)} labelled states of cells 1..16, listed by age (steps since the last event); the center value is the parity of the age -/",
       "def trapBucket (a : Nat) : List Nat :="]
for age in range(10):
    b = sorted(s_ for a, (c, s_) in S if a == age)
    out.append(f"  if a = {age} then [" + ", ".join(map(str, b)) + "] else")
out.append("  []"); out.append("")
open(os.path.join(root, 'lean', 'TrapData.lean'), 'w').write("\n".join(out))
print(len(S), "labelled states; distinct states", len(set(a for _, a in S)), "of", len(C))
