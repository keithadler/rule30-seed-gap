"""Write lean/WallData.lean: the four closed sets ("walls") as Lean lists of (phase, boundary value, strip).
Reads the certificates in results/p2/walls/ (lines: boundary-value strip; strip has cell 1 as its lowest bit).
The phase is found here by a search; Lean re-checks everything about it, so this script is not trusted."""
import math, sys, os
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.join(here, '..', '..')
def load(fn):
    k = None; C = set()
    for line in open(fn):
        if line.startswith('#'): k = int(line.split('k=')[1].split()[0]); continue
        p, s = line.split(); C.add((int(p), int(s)))
    return k, C
def nxt(c, s, f, k):
    full = s | (f << k)
    return (1 - c, (((s << 1) | c) ^ (full | (full >> 1))) & ((1 << k) - 1))
out = ["/-! Generated by `src/p2/mkwalls.py` from `results/p2/walls/`. Data only; `Wall.lean` checks it. -/", ""]
for name in ("T2", "T2b", "T2c", "T25"):
    k, C = load(os.path.join(root, 'results', 'p2', 'walls', f'cert_{name}.txt'))
    start = min(C); phi = {start: 0}; q = [start]; m = 0
    while q:
        a = q.pop()
        for f in (0, 1):
            b = nxt(a[0], a[1], f, k)
            if b not in phi: phi[b] = phi[a] + 1; q.append(b)
    for a in C:
        for f in (0, 1): m = math.gcd(m, phi[a] + 1 - phi[nxt(a[0], a[1], f, k)])
    w = 0
    for a in C:
        if a[1] & 1: w |= 1 << (phi[a] % m)
    items = sorted((phi[a] % m, a[0], a[1]) for a in C)
    out.append(f"/-- wall {name}: {len(C)} states of cells 1..{k}; period {m} in time; column 1 by phase is the bits of {w} -/")
    out.append(f"def wall{name} : List (Nat × Bool × Nat) := [")
    out.append(",\n".join("  " + ", ".join(f"({p}, {'true' if c else 'false'}, {s})" for p, c, s in items[i:i+4]) for i in range(0, len(items), 4)))
    out.append("]"); out.append(f"def wall{name}_k : Nat := {k}"); out.append(f"def wall{name}_m : Nat := {m}"); out.append(f"def wall{name}_w : Nat := {w}"); out.append("")
    print(name, "k", k, "states", len(C), "period", m, "label word", w, "first boundary-0 state", min(s for c, s in C if c == 0))
open(os.path.join(root, 'lean', 'WallData.lean'), 'w').write("\n".join(out))
